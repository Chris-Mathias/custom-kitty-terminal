#!/usr/bin/env bash
# Installs this setup (kitty + Claude Code) for the current user.
#
# Every file becomes a symbolic link into this repository, so a `git pull`
# here updates everything. Whatever was there before is kept with the
# .bak-<date> suffix. Your choices (language, theme, font) live in
# ~/.config/custom-kitty-terminal/settings.json and are changed with `ct config`.
# Claude Code's settings.json isn't replaced: only the keys this project owns
# (theme, spinner verbs, status lines) are merged into it. Claude's response
# style is left alone.
#
# Also migrates an install made by the older Portuguese version of this repo.
#
# Usage: ./install.sh
set -euo pipefail

REPO=$(cd "$(dirname "$0")" && pwd)
DATE=$(date +%Y%m%d-%H%M%S)
migrated=0

green=$'\e[32m'; yellow=$'\e[33m'; dim=$'\e[2m'; r=$'\e[0m'
ok()   { printf '%s✓%s %s\n' "$green" "$r" "$1"; }
warn() { printf '%s!%s %s\n' "$yellow" "$r" "$1"; }

# Links $2 -> $1 (a file in this repository), keeping whatever was there.
link() {
  local source=$1 target=$2
  mkdir -p "$(dirname "$target")"
  if [[ -L $target && $(readlink -f "$target") == "$(readlink -f "$source")" ]]; then
    printf '%s  already linked: %s%s\n' "$dim" "$target" "$r"; return
  fi
  if [[ -L $target && $(readlink "$target") == "$REPO"/* ]]; then
    rm "$target"  # our own link from an older layout: nothing to keep
  elif [[ -e $target || -L $target ]]; then
    mv "$target" "$target.bak-$DATE"
    warn "kept the previous one as $target.bak-$DATE"
  fi
  ln -s "$source" "$target"
  ok "$target"
}

# Removes a link left by the Portuguese version (only if it points into this repo).
unlink_old() {
  local target=$1
  if [[ -L $target ]]; then
    case $(readlink "$target") in
      "$REPO"/*) rm "$target"; migrated=1; ok "removed old link $target"; return ;;
    esac
  fi
  if [[ -e $target || -L $target ]]; then
    warn "left $target alone: it isn't a link into this repository"
  fi
}

echo "== Dependencies"
for cmd in kitty jq git python3 claude; do
  if command -v "$cmd" >/dev/null; then ok "$cmd"; else warn "$cmd not found (see the README)"; fi
done
fc-list : family 2>/dev/null | grep -qi "adwaita mono" || warn "Adwaita Mono font not found; pick another one with: ct config"

echo; echo "== Old Portuguese layout"
for f in abas.conf fechar_aba.py fechar-aba-dialogo.sh salvar_sessao.py; do unlink_old "$HOME/.config/kitty/$f"; done
for f in claude-painel claude-restaurar; do unlink_old "$HOME/.local/bin/$f"; done
unlink_old "$HOME/.local/share/claude-mods/painel-sessao"
# Response styles this project used to install (it no longer touches Claude's response style).
# (Not part of the Portuguese upgrade, so it doesn't count for the restart note below.)
was_migrated=$migrated
for f in portugues-conciso.md concise-english.md; do unlink_old "$HOME/.claude/output-styles/$f"; done
migrated=$was_migrated

echo; echo "== kitty (~/.config/kitty)"
for f in kitty.conf tabs.conf tab_bar.py close_tab.py close-tab-dialog.sh save_session.py; do
  link "$REPO/kitty/$f" "$HOME/.config/kitty/$f"
done
session="$HOME/.config/kitty/last-session.kitty-session"
old_session="$HOME/.config/kitty/ultima-sessao.kitty-session"
if [[ -f $old_session ]]; then
  sed 's/claude-restaurar/claude-restore/g' "$old_session" > "$session"
  rm "$old_session"
  ok "$session (converted from ultima-sessao.kitty-session)"
elif [[ ! -e $session ]]; then
  printf '# Generated by save_session.py — the tabs that were open last time.\nnew_tab\nlaunch\n' > "$session"
  ok "$session (empty; kitty fills it in)"
fi

echo; echo "== Commands (~/.local/bin)"
for f in ct ct-config ckt-apply claude-panel claude-restore; do
  link "$REPO/bin/$f" "$HOME/.local/bin/$f"
done
case ":$PATH:" in *":$HOME/.local/bin:"*) ;; *) warn "~/.local/bin isn't on your PATH; add it in ~/.zshrc";; esac

echo; echo "== Claude Code (~/.claude)"
link "$REPO/claude/statusline.sh" "$HOME/.claude/statusline.sh"
link "$REPO/claude/subagent-statusline.sh" "$HOME/.claude/subagent-statusline.sh"
for t in "$REPO"/themes/*/; do
  id=$(basename "$t")
  link "$REPO/themes/$id/claude.json" "$HOME/.claude/themes/$id.json"
done
link "$REPO/claude/session-panel" "$HOME/.local/share/claude-mods/session-panel"

echo; echo "== Your settings"
settings="$HOME/.config/custom-kitty-terminal/settings.json"
claude_settings="$HOME/.claude/settings.json"
if [[ ! -f $settings ]]; then
  lang=en
  # Coming from the Portuguese version: keep Portuguese.
  [[ $(jq -r '.outputStyle // empty' "$claude_settings" 2>/dev/null) == "Português conciso" ]] && lang=pt
  mkdir -p "$(dirname "$settings")"
  printf '{\n  "language": "%s",\n  "theme": "fedora",\n  "font_family": "Adwaita Mono",\n  "font_size": 12\n}\n' "$lang" > "$settings"
  ok "$settings (language: $lang)"
else
  printf '%s  kept: %s%s\n' "$dim" "$settings" "$r"
fi

before=""
[[ -f $claude_settings ]] && before=$(cat "$claude_settings")
# Drop a response style this project set before; one you picked yourself stays.
if [[ -f $claude_settings ]] && jq -e '.outputStyle == "Português conciso" or .outputStyle == "Concise English"' "$claude_settings" >/dev/null 2>&1; then
  jq 'del(.outputStyle)' "$claude_settings" > "$claude_settings.tmp" && cat "$claude_settings.tmp" > "$claude_settings" && rm "$claude_settings.tmp"
  ok "removed the response style this project had set in $claude_settings"
fi
"$REPO/bin/ckt-apply" || warn "couldn't apply everything (see above)"
if [[ -n $before && $(cat "$claude_settings") != "$before" ]]; then
  printf '%s\n' "$before" > "$claude_settings.bak-$DATE"
  ok "$claude_settings (merged; previous one in $claude_settings.bak-$DATE)"
fi
ok "kitty theme and font (~/.config/kitty/generated)"

echo; echo "== Shell (~/.zshrc, ~/.bashrc)"
# The `claude` function goes into the startup file of zsh and/or bash: the ones
# that exist, plus the one of your login shell.
rc_files=()
[[ -f $HOME/.zshrc || ${SHELL:-} == */zsh ]] && rc_files+=("$HOME/.zshrc")
[[ -f $HOME/.bashrc || ${SHELL:-} == */bash ]] && rc_files+=("$HOME/.bashrc")
for rc in "${rc_files[@]}"; do
python3 -I - "$rc" <<'PY'
import re, sys
from pathlib import Path

path = Path(sys.argv[1])
text = path.read_text() if path.exists() else ""
# The function added by hand for the Portuguese version.
text = re.sub(r"\n*# Claude Code com o painel lateral \(custom-kitty-terminal\)\nclaude\(\) \{\n(?:.*\n)*?\}\n", "\n", text)
# Our own block, rewritten on every run.
text = re.sub(r"\n*# >>> custom-kitty-terminal >>>\n(?:.*\n)*?# <<< custom-kitty-terminal <<<\n", "\n", text)
block = """# >>> custom-kitty-terminal >>>
# `claude` opens Claude Code with the side panel (managed by install.sh).
claude() {
  local panel="$HOME/.local/share/claude-mods/session-panel"
  if [[ -d $panel ]]; then command claude --plugin-dir "$panel" "$@"
  else command claude "$@"; fi
}
# <<< custom-kitty-terminal <<<
"""
text = text.rstrip("\n")
path.write_text((text + "\n\n" if text else "") + block)
PY
ok "$rc (claude loads the side panel)"
done

echo
if (( migrated )); then
  # kitty windows opened before the update keep saving tabs the old way until kitty restarts.
  warn "Upgraded from the Portuguese version: open a new tab (Ctrl+N) in each kitty window first,"
  warn "so the new tab saver records your tabs, then close and reopen kitty."
fi
ok "Done. Close and reopen kitty to finish. Settings: ct config (or the ⚙ in the tab bar)."
