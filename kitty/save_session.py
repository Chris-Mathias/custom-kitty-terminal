# kitty watcher: saves the open tabs to last-session.kitty-session so that
# the next time kitty starts everything comes back the same (startup_session in kitty.conf).
#
# For each window it saves the folder and, if Claude Code runs in it, which
# conversation (from the record in ~/.claude/sessions/<pid>.json). On restore,
# that window resumes the same conversation through claude-restore.
#
# Saves shortly after each change (focus, title, command starting or ending,
# window closed). When the whole kitty window is closed with the button,
# nothing is left open and the save is skipped, so the last snapshot is kept.
import json
import os
import shlex

from kitty.fast_data_types import add_timer, get_boss, remove_timer

SESSION_FILE = os.path.expanduser('~/.config/kitty/last-session.kitty-session')
# Written by the older Portuguese version; a kitty started before the update may still write it.
OLD_SESSION_FILE = os.path.expanduser('~/.config/kitty/ultima-sessao.kitty-session')
CLAUDE_SESSIONS = os.path.expanduser('~/.claude/sessions')
RESTORE = os.path.expanduser('~/.local/bin/claude-restore')
SHELL = os.environ.get('SHELL', '/usr/bin/zsh')
DELAY = 1.5  # seconds

_timer = None


def _claude_conversation(window):
    """sessionId of the Claude Code running in this window, if any."""
    try:
        procs = window.child.foreground_processes
    except Exception:
        return None
    for p in procs:
        try:
            with open(os.path.join(CLAUDE_SESSIONS, f"{p['pid']}.json")) as f:
                return json.load(f).get('sessionId')
        except Exception:
            continue
    return None


def _folder(window):
    try:
        return window.cwd_of_child or window.child.current_cwd or os.path.expanduser('~')
    except Exception:
        return os.path.expanduser('~')


def _tab_line(tab) -> str:
    """new_tab, with the name the tab was given by hand (double-click or set_tab_title)."""
    name = ' '.join((getattr(tab, 'name', '') or '').split())
    return f'new_tab {name}' if name else 'new_tab'


def _save(timer_id=None):
    global _timer
    _timer = None
    boss = get_boss()
    os_windows = [tm for tm in boss.os_window_map.values() if len(tm.tabs)]
    if not os_windows:
        return  # kitty is closing: keep the last snapshot
    lines = ['# Generated by save_session.py — the tabs that were open last time.']
    for n, tm in enumerate(os_windows):
        if n:
            lines.append('new_os_window')
        active = tm.active_tab
        for tab in tm.tabs:
            windows = [w for w in tab if not w.overlay_parent]
            if not windows:
                continue
            lines.append('')
            lines.append(_tab_line(tab))
            lines.append(f'layout {tab.current_layout.name}')
            for w in windows:
                lines.append(f'cd {shlex.quote(_folder(w))}')
                conversation = _claude_conversation(w)
                if conversation:
                    cmd = f'{RESTORE} {conversation}'
                    lines.append(f'launch {shlex.quote(SHELL)} -ic {shlex.quote(cmd)}')
                else:
                    lines.append('launch')
                # "focus" marks the tab and window that were in front
                if tab is active and w is tab.active_window:
                    lines.append('focus')
    text = '\n'.join(lines) + '\n'
    tmp = SESSION_FILE + '.tmp'
    with open(tmp, 'w') as f:
        f.write(text)
    os.replace(tmp, SESSION_FILE)
    try:
        os.remove(OLD_SESSION_FILE)
    except OSError:
        pass


def _schedule():
    global _timer
    if _timer is not None:
        remove_timer(_timer)
    _timer = add_timer(_save, DELAY, False)


def on_focus_change(boss, window, data):
    if data.get('focused'):
        _schedule()


def on_title_change(boss, window, data):
    _schedule()


def on_cmd_startstop(boss, window, data):
    _schedule()


def on_close(boss, window, data):
    _schedule()
